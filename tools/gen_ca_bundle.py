#!/usr/bin/env python3
"""Generate the certificate bundle (ESP32) or store (ESP8266) from the system CA certificates.

Reads the PEM CA certificates (default: /etc/ssl/certs/ca-certificates.crt from the Debian package ca-certificates).

ESP32: writes the bundle format of the Arduino-ESP32 WiFiClientSecure (esp_crt_bundle.c):

    uint16 number of certificates (big endian)
    for each certificate, sorted by subject name:
        uint16 subject name length, uint16 public key length
        subject name (DER), public key (DER, SubjectPublicKeyInfo)

ESP8266: writes a C header for src/common/castore8266.cpp (BearSSL finds the trust anchor by the SHA-256 of the
subject name, as the CertStore of the ESP8266 core):

    CA_STORE_NUM                         number of certificates
    CA_STORE_HASH[CA_STORE_NUM][32]      SHA-256 of the subject name (DER), PROGMEM
    CA_STORE_POS[CA_STORE_NUM + 1]       start of each certificate in CA_STORE_DER (last: end), PROGMEM
    CA_STORE_DER[]                       the certificates (DER), PROGMEM

Only Python standard library (small DER parser), because the PlatformIO venv has no cryptography module.

Usage:

    As PlatformIO extra script (pre:), it writes fw/.pio/ca_bundle/x509_crt_bundle.bin (ESP32) or
    fw/.pio/ca_store/ca_store.h (ESP8266, also added to the include path) before the build.
    Standalone: gen_ca_bundle.py [input.pem] output.bin|output.h
"""

import base64
import hashlib
import os
import re
import sys

DEFAULT_INPUT = "/etc/ssl/certs/ca-certificates.crt"


def der_tlv(buf, pos):
    """Parse one DER element at pos, return (tag, content start, end)"""
    tag = buf[pos]
    length = buf[pos + 1]
    start = pos + 2
    if length & 0x80:
        num = length & 0x7f
        length = int.from_bytes(buf[start:(start + num)], "big")
        start += num
    return tag, start, (start + length)


def cert_name_key(der):
    """Get subject name and public key (both DER) of a certificate"""
    _, cert_start, _ = der_tlv(der, 0)          # Certificate
    _, pos, _ = der_tlv(der, cert_start)         # TBSCertificate
    fields = []
    while len(fields) < 7:
        tag, _, end = der_tlv(der, pos)
        fields.append((tag, pos, end))
        pos = end
    # Skip optional version [0]
    if fields[0][0] == 0xa0:
        fields = fields[1:]
    # serial, signature, issuer, validity, subject, subjectPublicKeyInfo
    subject = der[fields[4][1]:fields[4][2]]
    pubkey = der[fields[5][1]:fields[5][2]]
    return subject, pubkey


def read_certs(pem_text):
    """Get the certificates (DER) of PEM text"""
    return [base64.b64decode(b64) for b64 in
            re.findall(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", pem_text, re.S)]


def c_bytes(data, indent="    "):
    """Format bytes as C array lines"""
    return "\n".join(indent + ", ".join("0x{:02x}".format(val) for val in data[pos:(pos + 16)]) + ","
                     for pos in range(0, len(data), 16))


def make_store(pem_text):
    """Make the ESP8266 store header from PEM text"""
    ders = read_certs(pem_text)
    hashes = [hashlib.sha256(cert_name_key(der)[0]).digest() for der in ders]
    pos = [0]
    for der in ders:
        pos.append(pos[-1] + len(der))
    lines = ["// Generated by tools/gen_ca_bundle.py from {}, do not edit".format(DEFAULT_INPUT),
             "",
             "static constexpr uint32_t CA_STORE_NUM = {};".format(len(ders)),
             "",
             "static const uint8_t CA_STORE_HASH[CA_STORE_NUM][32] PROGMEM = {"]
    lines += ["    {{ {} }},".format(", ".join("0x{:02x}".format(val) for val in digest)) for digest in hashes]
    lines += ["};", "", "static const uint32_t CA_STORE_POS[CA_STORE_NUM + 1] PROGMEM = {"]
    lines += ["    " + ", ".join(str(val) for val in pos[ix:(ix + 10)]) + "," for ix in range(0, len(pos), 10)]
    lines += ["};", "", "static const uint8_t CA_STORE_DER[] PROGMEM = {", c_bytes(b"".join(ders)), "};", ""]
    return "\n".join(lines).encode("ascii"), len(ders)


def make_bundle(pem_text):
    """Make the bundle from PEM text"""
    certs = [cert_name_key(der) for der in read_certs(pem_text)]
    certs.sort(key=lambda cert: cert[0])
    out = bytearray(len(certs).to_bytes(2, "big"))
    for name, key in certs:
        out += len(name).to_bytes(2, "big") + len(key).to_bytes(2, "big") + name + key
    return bytes(out), len(certs)


def generate(input_path, output_path):
    """Generate bundle file if input is newer"""
    if os.path.exists(output_path) and (os.path.getmtime(output_path) >= os.path.getmtime(input_path)):
        return
    with open(input_path, "r", encoding="ascii") as fh:
        make = (make_store if output_path.endswith(".h") else make_bundle)
        bundle, num = make(fh.read())
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "wb") as fh:
        fh.write(bundle)
    print("CA bundle: {} certificates, {} bytes -> {}".format(num, len(bundle), output_path))


try:
    Import("env")  # noqa: F821 (PlatformIO SCons)
    _env = env  # noqa: F821
    if _env["PIOPLATFORM"] == "espressif8266":
        _dir = os.path.join(_env["PROJECT_DIR"], ".pio", "ca_store")
        generate(DEFAULT_INPUT, os.path.join(_dir, "ca_store.h"))
        _env.Append(CPPPATH=[_dir])
    else:
        generate(DEFAULT_INPUT, os.path.join(_env["PROJECT_DIR"], ".pio", "ca_bundle", "x509_crt_bundle.bin"))
except NameError:
    if __name__ == "__main__":
        if len(sys.argv) not in (2, 3):
            print(__doc__)
            sys.exit(1)
        generate(*(([DEFAULT_INPUT] if (len(sys.argv) == 2) else []) + sys.argv[1:]))
