#!/usr/bin/env python3
"""Firmware name and version for PlatformIO builds.

Name: the PlatformIO env name, laempli-<type>, e.g. laempli-chlotz. The device IDs are <type>-<6 hex chars>.

Version: <timestamp yyyymmddhhmmss>-<git short hash>[-dirty], e.g. 20261023012737-9e085f6. It sorts by time.

- Clean work tree: timestamp of the commit (same commit gives the same version)
- Uncommitted changes: "-dirty" and the build time (each development build is newer)

As PlatformIO extra script (pre:):

- Writes the header fw_version.h (FW_NAME, FW_TYPE, FW_VERSION, FW_HASH, FW_TIME) to <build dir>/fw_version/ and
  adds it to the include path. The header is only written if it changes.
- After the build, copies firmware.bin to data/fw/<name>_<version>.bin. The backend serves the newest file of each
  name for OTA updates. Only the newest KEEP_FILES files of each name stay.

Standalone: version.py prints the version.
"""

import glob
import os
import re
import shutil
import subprocess
import time

# Firmware files to keep for each name
KEEP_FILES = 10


def git(*args, cwd=None):
    """Run git, return output"""
    return subprocess.run(["git"] + list(args), cwd=cwd, capture_output=True, text=True, check=True).stdout.strip()


def get_version(cwd=None):
    """Get version info dict"""
    try:
        commit = git("rev-parse", "--short=7", "HEAD", cwd=cwd)
        dirty = (git("status", "--porcelain", "--untracked-files=no", cwd=cwd) != "")
        if dirty:
            stamp = time.strftime("%Y%m%d%H%M%S")
        else:
            stamp = git("log", "-1", "--format=%cd", "--date=format-local:%Y%m%d%H%M%S", cwd=cwd)
    except (OSError, subprocess.CalledProcessError):
        commit, dirty, stamp = "unknown", True, time.strftime("%Y%m%d%H%M%S")
    hash_ = commit + ("-dirty" if dirty else "")
    return {"version": "{}-{}".format(stamp, hash_), "hash": hash_, "time": stamp}


def write_if_changed(path, text):
    """Write file only if content changes"""
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as fh:
            if fh.read() == text:
                return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def file_time(path):
    """Get timestamp of firmware file"""
    # Also old names <hash>-<time>
    match = re.search(r"[0-9]{14}", os.path.basename(path))
    return (match.group(0) if match else "")


def prune_files(dirname, name, keep):
    """Remove all but the newest firmware files of name"""
    files = glob.glob(os.path.join(dirname, name + "_*.bin"))
    files.sort(key=file_time)
    for path in files[:-keep]:
        os.unlink(path)


try:
    Import("env")  # noqa: F821 (PlatformIO SCons)
    _env = env  # noqa: F821
    _info = get_version(_env["PROJECT_DIR"])
    _name = _env["PIOENV"]
    if not _name.startswith("laempli-"):
        raise SystemExit("version.py: env name must be laempli-<type>, not " + _name)
    _info.update(name=_name, type=_name[len("laempli-"):])
    _incdir = os.path.join(_env.subst("$BUILD_DIR"), "fw_version")
    write_if_changed(os.path.join(_incdir, "fw_version.h"),
                     "// Generated by tools/version.py\n"
                     "#define FW_NAME \"{name}\"\n#define FW_TYPE \"{type}\"\n"
                     "#define FW_VERSION \"{version}\"\n#define FW_HASH \"{hash}\"\n#define FW_TIME \"{time}\"\n"
                     .format(**_info))
    _env.Append(CPPPATH=[_incdir])
    print("Firmware: {name} {version}".format(**_info))

    def _copy_bin(target, source, env):
        # PROJECT_DIR is fw/, data/ is at the repo root
        fwdir = os.path.join(os.path.dirname(env["PROJECT_DIR"]), "data", "fw")
        os.makedirs(fwdir, exist_ok=True)
        dest = os.path.join(fwdir, "{name}_{version}.bin".format(**_info))
        shutil.copyfile(target[0].get_abspath(), dest)
        prune_files(fwdir, _info["name"], KEEP_FILES)
        print("Firmware file: " + os.path.relpath(dest, env["PROJECT_DIR"]))

    _env.AddPostAction("$BUILD_DIR/${PROGNAME}.bin", _copy_bin)
except NameError:
    if __name__ == "__main__":
        print(get_version()["version"])
